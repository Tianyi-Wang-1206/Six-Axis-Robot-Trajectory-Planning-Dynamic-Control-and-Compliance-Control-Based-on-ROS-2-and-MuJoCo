#!/usr/bin/env python3
"""Derive the planning URDF with finger collision boxes covering the full stroke.
The articulated URDF remains the dynamics source.
"""
from pathlib import Path
import struct
import xml.etree.ElementTree as ET


def main():
    package = Path(__file__).resolve().parents[1]
    root = ET.parse(package / 'urdf/lite6.urdf').getroot()
    root.remove(root.find('ros2_control'))
    for side in ('left', 'right'):
        name = f'gripper_{side}_finger'
        joint = root.find(f"joint[@name='{name}']")
        limit = joint.find('limit')
        low, high = float(limit.get('lower')), float(limit.get('upper'))
        joint.set('type', 'fixed')
        for tag in ('axis', 'limit', 'dynamics'):
            joint.remove(joint.find(tag))
        link = root.find(f"link[@name='{name}']")
        for collision in link.findall('collision'):
            mesh = collision.find('geometry/mesh')
            path = package / mesh.get('filename').split('lite6_description/')[1]
            raw = path.read_bytes()
            count = struct.unpack_from('<I', raw, 80)[0]
            assert len(raw) == 84 + 50 * count
            vertices = []
            for i in range(count):
                values = struct.unpack_from('<12f', raw, 84 + 50*i)
                vertices.extend(values[j:j+3] for j in (3, 6, 9))
            lo = [min(v[i] for v in vertices) for i in range(3)]
            hi = [max(v[i] for v in vertices) for i in range(3)]
            lo[1] += low
            hi[1] += high
            # A micrometre pad contains mesh conversion/rounding error.
            size = [hi[i] - lo[i] + 2e-6 for i in range(3)]
            center = [(hi[i] + lo[i])/2 for i in range(3)]
            geometry = collision.find('geometry')
            geometry.remove(mesh)
            ET.SubElement(geometry, 'box', size=' '.join(map(str, size)))
            ET.SubElement(collision, 'origin', xyz=' '.join(map(str, center)), rpy='0 0 0')
    ET.indent(root, space='  ')
    output = package / 'urdf/lite6_arm.urdf'
    output.write_text('<?xml version="1.0"?>\n'
                      '<!-- GENERATED by tools/generate_arm_model.py; planning/FK only. -->\n'
                      + ET.tostring(root, encoding='unicode') + '\n')


if __name__ == '__main__':
    main()
